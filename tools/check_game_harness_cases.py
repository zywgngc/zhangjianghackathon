"""Inventory the three original harness cases without running or reducing them.

Uses only the standard library. It loads benchmarks.py in isolation and maps
Windows-safe snapshot names in that module's in-memory CASES constant. It does
not import harness settings, inspect credentials, call models, or use a network.
"""

import argparse
import ast
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath, PureWindowsPath
import sys
import uuid


WORKSPACE = Path(__file__).resolve().parents[1]
DEFAULT_HARNESS_ROOT = WORKSPACE
DEFAULT_OUTPUT = WORKSPACE / "output/harness-cases-preflight.json"


def _within(root, relative):
    """Resolve a snapshot-owned relative file, without accepting traversal."""
    portable = PurePosixPath(str(relative).replace("\\", "/"))
    if portable.is_absolute() or PureWindowsPath(str(relative)).drive or ".." in portable.parts:
        raise ValueError("Snapshot path must be relative to the harness root")
    path = root.joinpath(*portable.parts).resolve(strict=True)
    path.relative_to(root)
    return path


def _load_benchmarks(path):
    name = "harness_cases_preflight_" + uuid.uuid4().hex
    spec = importlib.util.spec_from_file_location(name, str(path))
    module = importlib.util.module_from_spec(spec)
    previous = sys.dont_write_bytecode
    try:
        # Keep the source snapshot read-only, including generated bytecode.
        sys.dont_write_bytecode = True
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    if not isinstance(getattr(module, "CASES", None), dict) or not callable(getattr(module, "inventory", None)):
        raise ValueError("benchmarks.py must expose CASES and inventory(root)")
    return module


def _manifest(root):
    path = root / "_snapshot_manifest.json"
    if not path.is_file():
        return {}, None
    document = json.loads(path.read_text(encoding="utf-8-sig"))
    files = document.get("files")
    if not isinstance(files, list):
        raise ValueError("Snapshot manifest files must be a list")
    mapping = {}
    for item in files:
        source, local = item.get("source_path"), item.get("local_path")
        if not isinstance(source, str) or not isinstance(local, str):
            raise ValueError("Snapshot manifest requires source_path/local_path")
        if source in mapping and mapping[source] != local:
            raise ValueError("Conflicting snapshot path mapping")
        mapping[source] = local
    return mapping, {"path": str(path), "branch": document.get("branch"), "commit": document.get("commit")}


def _input_contract(root):
    path = root / "game_harness/schemas.py"
    if not path.is_file():
        return {"inspection": "unavailable", "source": str(path)}
    tree = ast.parse(path.read_text(encoding="utf-8-sig"), filename=str(path))
    result = {"inspection": "static_ast", "source": str(path), "run_request_fields": []}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or node.name != "RunRequest":
            continue
        for field in node.body:
            if not isinstance(field, ast.AnnAssign) or not isinstance(field.target, ast.Name):
                continue
            name = field.target.id
            result["run_request_fields"].append(name)
            if name == "description" and isinstance(field.value, ast.Call):
                for argument in field.value.keywords:
                    if argument.arg == "max_length":
                        result["max_description_characters"] = ast.literal_eval(argument.value)
            if name == "engine" and isinstance(field.annotation, ast.Subscript):
                try:
                    values = ast.literal_eval(field.annotation.slice)
                    result["accepted_engine_values"] = list(values) if isinstance(values, tuple) else [values]
                except (ValueError, TypeError):
                    pass
    image_fields = {"images", "image_refs", "imageRefs", "reference_images", "attachments"}
    result["reference_images_exposed_in_run_request"] = bool(image_fields.intersection(result["run_request_fields"]))
    return result


def build_report(harness_root):
    root = Path(harness_root).expanduser().resolve(strict=True)
    benchmarks_path = _within(root, "game_harness/benchmarks.py")
    original_benchmarks = benchmarks_path.read_bytes()
    module = _load_benchmarks(benchmarks_path)
    source_cases = dict(module.CASES)
    manifest, provenance = _manifest(root)
    mapped_cases, mappings = {}, {}
    for case_id, (source_directory, source_filename) in source_cases.items():
        source = str(PurePosixPath(source_directory) / source_filename)
        if source in manifest:
            local = manifest[source]
            method = "snapshot_manifest"
        else:
            # Exact, reversible mapping used by this repository's API snapshot.
            # No case-name inference or source-text rewriting is performed.
            local = str(PurePosixPath(source_directory.replace(":", "_")) / source_filename)
            method = "source_directory_colon_to_underscore"
            if not (root / local).is_file() and (root / source).is_file():
                local, method = source, "unchanged_source_path"
        actual = _within(root, local)
        relative = actual.relative_to(root)
        mapped_cases[case_id] = (relative.parent.as_posix(), relative.name)
        mappings[case_id] = {
            "source_directory": source_directory, "source_path": source,
            "local_path": relative.as_posix(), "actual_path": str(actual), "method": method,
        }
    # This is the only adaptation of the loaded upstream module. Files and
    # original case specifications remain unchanged.
    module.CASES = mapped_cases
    cases = module.inventory(root)
    if benchmarks_path.read_bytes() != original_benchmarks:
        raise ValueError("benchmarks.py changed during preflight")
    if {case["case_id"] for case in cases} != set(source_cases):
        raise ValueError("Inventory did not preserve the original case IDs")
    contract = _input_contract(root)
    for case in cases:
        mapping = mappings[case["case_id"]]
        case["path_mapping"] = mapping
        case["source_specification"] = mapping["source_path"]
        case["actual_specification"] = mapping["actual_path"]
        case["reference_images_attached_to_main_input"] = False
        for image in case["reference_images"]:
            actual_image = _within(root, image["path"])
            local_image = actual_image.relative_to(root).as_posix()
            sources = [source for source, local in manifest.items() if local.replace("\\", "/") == local_image]
            image["source_path"] = sources[0] if sources else str(PurePosixPath(mapping["source_directory"]) / actual_image.name)
            image["actual_path"] = str(actual_image)
    return {
        "reportVersion": "1.0", "kind": "main_harness_original_cases_preflight",
        "generatedAt": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "harness_root": str(root), "snapshot": provenance,
        "inventory_source": {"path": str(benchmarks_path), "sha256": hashlib.sha256(original_benchmarks).hexdigest(), "method": "importlib_dynamic_load_with_in_memory_CASES_path_mapping"},
        "execution": "not_run", "models_called": False, "games_built": False,
        "games_played": False, "credentials_inspected": False, "network_requests": 0,
        "main_input_contract": contract,
        "scope_notes": [
            "This report inventories unchanged original specifications and image hashes; it does not run the main agent or claim any game passed acceptance tests.",
            "The three cases retain their explicit Babylon/Phaser and TypeScript/Vite requirements; no engine substitution or shortened specification is used.",
            "Reference PNGs are inventoried only. They were not attached to a main-agent request; the inspected RunRequest currently exposes description and engine fields only.",
            "Engine adapters, long-spec input, multi-file TypeScript builds and reference-image input are main-harness capabilities. They are not failures of the material portal.",
            "API credentials are deliberately not inspected by this script; no model request or provider configuration check is performed.",
        ],
        "material_portal_is_blocker": False,
        "summary": {"case_count": len(cases), "blocked_count": sum(not case["runnable"] for case in cases), "executed_count": 0},
        "cases": cases,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--harness-root", type=Path, default=DEFAULT_HARNESS_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    try:
        report = build_report(args.harness_root)
        output = args.output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(json.dumps(report, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print("Preflight failed: {}".format(exc), file=sys.stderr)
        return 2
    for case in report["cases"]:
        print("{} chars={} engine={} blockers={}".format(case["case_id"], case["characters"], case["locked_engine"], ",".join(case["blockers"]) or "none"))
    print("Report: {}".format(output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
